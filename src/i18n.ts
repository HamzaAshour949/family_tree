export function isRtl(language: LanguageCode): boolean {
  return language === "ar";
}

export function translate(language: LanguageCode, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function useI18n() {
  const language = useFamilyStore((state) => state.language);
  const setLanguage = useFamilyStore((state) => state.setLanguage);
  return {
    direction: isRtl(language) ? "rtl" : "ltr",
    familyText: familyTextByLanguage[language],
    language,
    languageOptions,
    setLanguage,
    t: (key: TranslationKey) => translate(language, key),
  };
}
