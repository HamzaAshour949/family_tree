export function isRtl(language: LanguageCode): boolean {
  return language === "ar";
}

export function translate(language: LanguageCode, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function licenseDisplayText(license: LicenseState, language: LanguageCode): string {
  if (license.tier === "full" && license.status === "active") return translate(language, "full");
  if (license.tier === "trial") return translate(language, "trial");
  if (license.tier === "empty" || license.status === "inactive") return translate(language, "freeMode");
  return translate(language, license.status as TranslationKey);
}

export function useI18n() {
  const language = useFamilyStore((state) => state.language);
  const setLanguage = useFamilyStore((state) => state.setLanguage);
  return {
    direction: isRtl(language) ? "rtl" : "ltr",
    familyText: familyTextByLanguage[language],
    language,
    languageOptions,
    licenseText: (license: LicenseState) => licenseDisplayText(license, language),
    setLanguage,
    t: (key: TranslationKey) => translate(language, key),
  };
}